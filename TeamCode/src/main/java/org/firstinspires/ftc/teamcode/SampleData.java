package org.firstinspires.ftc.teamcode;

public class SampleData {
    public SampleData(String n, double x, double y, double h, double ratio) {
        name = n;
        this.x = x;
        this.y = y;
        heading = h;
        this.ratio = ratio;
    }

    public String name;
    public double x;
    public double y;
    public double heading;
    public double ratio;
}
